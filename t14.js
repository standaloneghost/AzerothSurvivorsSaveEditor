const { chromium } = require('playwright');
const fs = require('fs'), { execFileSync } = require('child_process');
const [url, save, flag] = process.argv.slice(2);
const dec = (f) => execFileSync('python3', ['-I', '../dec/show.py', f], { encoding: 'utf8' });
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
const ln = (t, k) => t.split('\n').find((l) => l.startsWith(k)) || '';
(async () => {
  const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1280, height: 900 } });
  const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  await p.goto(url); await p.waitForSelector('h2');
  const orig = dec(save);
  const box = await p.locator('button[data-a=caopen]').boundingBox();
  ok(Math.abs(box.x + box.width / 2 - 640) <= 1, 'button is dead center: ' + (box.x + box.width / 2));
  await p.click('button[data-a=caopen]');
  ok(await p.locator('[role=alertdialog]').count() === 1, 'dialog opens');
  ok((await p.textContent('.dialog')).includes('cannot be easily undone'), 'warning shown');
  ok(await p.evaluate(() => document.activeElement.id) === 'cacancel', 'Cancel has focus');
  await p.screenshot({ path: '../shots/ca.png' });
  await p.click('button[data-a=cacancel]');
  ok(await p.locator('[role=alertdialog]').count() === 0 && dec(save) === orig, 'Cancel changes nothing');
  await p.click('button[data-a=caopen]'); await p.keyboard.press('Escape');
  ok(await p.locator('[role=alertdialog]').count() === 0 && dec(save) === orig, 'Escape cancels');
  fs.writeFileSync(flag, '1');
  await p.waitForFunction(() => document.querySelector('.game').textContent.includes('running'), null, { timeout: 7000 });
  ok(await p.locator('button[data-a=caopen]').isDisabled(), 'disabled while game runs');
  fs.unlinkSync(flag);
  await p.waitForFunction(() => document.querySelector('.game').textContent.includes('closed'), null, { timeout: 7000 });
  await p.click('button[data-a=caopen]'); await p.click('button[data-a=caconfirm]');
  await p.waitForSelector('.banner.ok');
  ok((await p.textContent('.banner.ok')).includes('Complete All finished'), 'finished message');
  ok((await p.textContent('.pending')).includes('Nothing changed'), 'nothing left pending');
  const t = dec(save), classes = ['1', '2', '3', '4', '5', '7', '8', '9', '11'];
  ok(classes.every((c) => ln(t, `talent|${c}|`).split('|')[2] === '314500'), 'all 9 classes level 200');
  ok(ln(t, 'talent|8|').split('|')[3] === ln(orig, 'talent|8|').split('|')[3], 'talents kept');
  ok(classes.every((c) => ln(t, `beat|${c}|`).split('|')[2].split(',').length === 12), 'all zones cleared');
  ok(classes.every((c) => { const z = ln(t, `hbeat|${c}|`).split('|')[2].split(','); return z.length === 12 && z.every((x) => x.endsWith(':5')); }), 'all zones Heroic V');
  const items = ln(t, 'items|').slice(6).split(','), stars = ln(t, 'stars|').slice(6).split(',');
  const need = classes.flatMap((c) => { const n = ['4', '7'].includes(c) ? 10 : 9, o = []; for (let s = 0; s < n; s++) for (let r = 0; r < 6; r++) o.push(`1${c.padStart(2, '0')}${s}${r}0`); return o; });
  console.log('gear ids', need.length, 'items', items.length, 'stars', stars.length);
  ok(need.every((x) => items.includes(x)), 'all gear granted');
  const st = Object.fromEntries(stars.map((x) => x.split(':')));
  ok(need.every((x) => st[x] === '5'), 'all gear +5');
  ok(ln(orig, 'items|').slice(6).split(',').every((x) => items.includes(x)), 'no items lost');
  const a = ln(t, 'ach|').slice(4).split(','); ok(a.length >= 125, 'achievements ' + a.length);
  const keep = (x) => x.split('\n').filter((l) => !/^(talent|beat|hbeat|items|stars|ach|achat)\|/.test(l));
  ok(keep(orig).join('\n') === keep(t).join('\n'), 'every other line unchanged');
  ok(fs.readdirSync(save.replace('characters.txt', 'EditorBackups')).length === 1, 'backup made first');
  await p.setViewportSize({ width: 390, height: 844 });
  ok(await p.evaluate(() => document.documentElement.scrollWidth - innerWidth) <= 0, 'no sideways scroll at phone width');
  ok(errs.length === 0, 'no page errors ' + errs.join('|'));
  console.log(fails ? `${fails} FAILED` : 'ALL PASSED');
  await b.close();
})().catch((e) => { console.error(e); process.exit(1); });
