const { chromium } = require('playwright');
const fs = require('fs'), path = require('path');
const [url, dir, flag] = process.argv.slice(2);
const save = dir + '/characters.txt';
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
(async () => {
  const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1280, height: 900 } });
  const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  await p.goto(url); await p.waitForSelector('h2');
  const token = new URL(url).searchParams.get('t');
  await p.click('button[data-a=page][data-v=backups]');
  await p.waitForSelector('.dangerzone');
  ok(await p.evaluate(() => { const z = document.querySelector('.dangerzone'), r = document.querySelector('.box.rows'); return z.getBoundingClientRect().top > r.getBoundingClientRect().bottom; }), 'button sits below the backups');
  await p.click('button[data-a=wipeopen]');
  ok((await p.textContent('.bigwarn')).includes('THIS CANNOT BE UNDONE'), 'big warning shown');
  ok(await p.evaluate(() => document.activeElement.id) === 'wipecancel', 'Cancel has focus');
  ok(await p.locator('button[data-a=wipeconfirm]').isDisabled(), 'Delete disabled until checked');
  await p.screenshot({ path: '../shots/wipe.png' });
  await p.check('#wipeok');
  ok(await p.locator('button[data-a=wipeconfirm]').isEnabled(), 'checkbox enables Delete');
  await p.uncheck('#wipeok');
  ok(await p.locator('button[data-a=wipeconfirm]').isDisabled(), 'unchecking disables Delete');
  await p.check('#wipeok'); await p.click('button[data-a=wipecancel]');
  ok(fs.existsSync(save) && fs.existsSync(dir + '/Saves/Backup 1.sav'), 'Cancel deletes nothing');
  await p.click('button[data-a=wipeopen]');
  ok(await p.locator('button[data-a=wipeconfirm]').isDisabled(), 'checkbox resets on reopen');
  await p.keyboard.press('Escape');
  ok(await p.locator('[role=alertdialog]').count() === 0, 'Escape cancels');
  const call = (body, tok) => p.evaluate(async ([bd, t]) => (await fetch('/api/wipe', { method: 'POST', headers: { 'X-Token': t }, body: bd })).status, [body, tok]);
  ok(await call(JSON.stringify({ confirm: 'DELETE ALL SAVES' }), 'wrong') === 403, 'wipe refuses a bad token');
  ok(await call(JSON.stringify({ confirm: 'yes' }), token) === 400, 'wipe refuses without the exact confirmation');
  ok(fs.existsSync(save), 'save survives refused calls');
  fs.writeFileSync(flag, '1');
  ok(await call(JSON.stringify({ confirm: 'DELETE ALL SAVES' }), token) === 409, 'server refuses while the game runs');
  await p.waitForFunction(() => document.querySelector('.game').textContent.includes('running'), null, { timeout: 7000 });
  ok(await p.locator('button[data-a=wipeopen]').isDisabled(), 'button disabled while game runs');
  ok(fs.existsSync(save), 'save survives while game runs');
  fs.unlinkSync(flag);
  await p.waitForFunction(() => document.querySelector('.game').textContent.includes('closed'), null, { timeout: 7000 });
  await p.click('button[data-a=wipeopen]'); await p.check('#wipeok'); await p.click('button[data-a=wipeconfirm]');
  await p.waitForSelector('.fatal h2');
  ok((await p.textContent('.fatal h2')) === 'Saves deleted', 'done screen shown');
  console.log((await p.textContent('.fatal')).trim());
  const left = []; const walk = (d) => fs.readdirSync(d).forEach((f) => { const x = path.join(d, f); fs.statSync(x).isDirectory() ? (left.push(path.relative(dir, x) + '/'), walk(x)) : left.push(path.relative(dir, x)); }); walk(dir);
  console.log('left:', left.join(', '));
  ok(!fs.existsSync(save) && !fs.existsSync(dir + '/characters.before-test.txt') && !fs.existsSync(dir + '/characters.backup-at.txt'), 'save and root backups gone');
  ok(!left.some((f) => f.endsWith('.sav')) && !fs.existsSync(dir + '/EditorBackups'), 'all backups gone');
  ok(fs.existsSync(dir + '/hud.txt') && fs.existsSync(dir + '/meter.txt') && fs.existsSync(dir + '/Saves/notes.txt'), 'other files kept');
  ok(fs.existsSync('../outside-keep.txt'), 'nothing outside the folder touched');
  await p.waitForTimeout(4500);
  ok((await p.textContent('.fatal h2')) === 'Saves deleted', 'screen stays stable after a status check');
  ok(errs.length === 0, 'no page errors ' + errs.join('|'));
  console.log(fails ? `${fails} FAILED` : 'ALL PASSED');
  await b.close();
})().catch((e) => { console.error(e); process.exit(1); });
