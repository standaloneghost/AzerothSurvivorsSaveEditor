const { chromium } = require('playwright');
const fs = require('fs'), { execFileSync } = require('child_process');
const [url, save] = process.argv.slice(2);
const dec = (f) => execFileSync('python3', ['-I', '../dec/show.py', f], { encoding: 'utf8' });
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
const ln = (t, k) => t.split('\n').find((l) => l.startsWith(k + '|')) || '';
(async () => {
  const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1280, height: 900 } });
  const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  await p.goto(url); await p.waitForSelector('h2');
  const orig = dec(save);
  await p.click('button[data-a=page][data-v=rewards]');
  await p.click('button[data-a=rtab][data-v=Tabards]');
  ok(await p.locator('input[data-c=tabard]').count() === 15, '15 editable tabards');
  ok(await p.locator('input[data-c=tabard]:checked').count() === 13, 'current 13 ticked');
  ok((await p.textContent('main')).includes('Unlocked by Warsong Gulch'), 'battleground tabards show their achievement');
  await p.screenshot({ path: '../shots/tabards.png', fullPage: true });
  await p.check('input[data-c=tabard][data-k="90016"]');
  ok((await p.textContent('.pending')).includes('Tabard added: Scarlet Crusade Tabard'), 'pending shows tabard');
  await p.uncheck('input[data-c=tabard][data-k="90016"]');
  ok((await p.textContent('.pending')).includes('Nothing changed'), 'undo returns to identical text');
  await p.check('input[data-c=tabard][data-k="90025"]');
  await p.click('button[data-a=save]'); await p.waitForSelector('.banner.ok');
  let t = dec(save);
  ok(ln(t, 'tabard').endsWith(',90024,90025'), 'tabard saved in order');
  ok(t.split('\n').filter((l) => !orig.split('\n').includes(l)).length === 1, 'only tabard line changed');
  await p.click('button[data-a=caopen]');
  ok((await p.textContent('.dialog')).includes('race and tabard'), 'dialog mentions tabards');
  await p.click('button[data-a=caconfirm]'); await p.waitForSelector('.banner.ok');
  t = dec(save);
  const want = 'tabard|' + [...Array(15).keys()].map((i) => 90011 + i).join(',');
  ok(ln(t, 'tabard') === want, 'complete all grants all 15 tabards');
  ok(errs.length === 0, 'no page errors');
  console.log(fails ? `${fails} FAILED` : 'ALL PASSED');
  await b.close();
})().catch((e) => { console.error(e); process.exit(1); });
