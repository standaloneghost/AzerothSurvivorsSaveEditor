const { chromium } = require('playwright');
const { execFileSync } = require('child_process');
const [url, save] = process.argv.slice(2);
const dec = (f) => execFileSync('python3', ['-I', 'tools/show_save.py', f], { encoding: 'utf8' });
(async () => {
  const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1280, height: 900 } });
  const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  await p.goto(url); await p.waitForSelector('h2');
  const before = dec(save);
  const items = (t) => t.split('\n').find((l) => l.startsWith('items|')).slice(6).split(',');
  await p.screenshot({ path: 'tests/shots/layout.png', clip: { x: 230, y: 70, width: 1050, height: 420 } });
  await p.click('button[data-a=cls][data-v="4"]');
  await p.click('button[data-a=unlockall]');
  console.log('rogue count:', await p.textContent('.armor .count'), '| disabled now:', await p.locator('button[data-a=unlockall]').isDisabled());
  console.log('rogue weapon cells N/A:', await p.locator('.cell.na').count());
  await p.click('button[data-a=cls][data-v="2"]');
  await p.click('button[data-a=unlockall]');
  console.log('paladin:', await p.textContent('.armor .count'));
  await p.click('button[data-a=discard]');
  console.log('after discard:', await p.textContent('.armor .count'), '|', (await p.textContent('.pending')).trim());
  await p.click('button[data-a=unlockall]');
  await p.click('button[data-a=save]'); await p.waitForSelector('.banner.ok');
  const A = before.split('\n'), B = dec(save).split('\n');
  const a = items(before), c = items(dec(save));
  console.log('changed kinds:', [...new Set(B.filter((l) => !A.includes(l)).map((l) => l.split('|')[0]))].join());
  console.log('added', c.filter((x) => !a.includes(x)).join(), '| stars same', A.find((l) => l.startsWith('stars|')) === B.find((l) => l.startsWith('stars|')), '| errors', errs.length);
  await p.setViewportSize({ width: 390, height: 844 });
  console.log('phone overflow', await p.evaluate(() => document.documentElement.scrollWidth - innerWidth));
  await b.close();
})();
