const { chromium } = require('playwright');
const { execFileSync } = require('child_process');
const [url, save] = process.argv.slice(2);
const dec = (f) => execFileSync('python3', ['-I', 'tools/show_save.py', f], { encoding: 'utf8' });
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
const items = (t) => t.split('\n').find((l) => l.startsWith('items|')).slice(6).split(',');
(async () => {
  const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1280, height: 1000 } });
  const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  await p.goto(url); await p.waitForSelector('h2');
  const orig = dec(save);
  const go = (c) => p.click(`button[data-a=cls][data-v="${c}"]`);
  const count = () => p.textContent('.armor .count');
  await go('4');
  ok((await count()).includes('of 60'), 'rogue: ' + await count());
  ok(await p.locator('.cell.na').count() === 0, 'no N/A cells');
  ok(await p.locator('.armor tbody tr').count() === 10, 'rogue has 10 rows');
  ok((await p.textContent('.armor')).includes('Off Hand') && !(await p.textContent('.armor')).includes("can't be edited"), 'off hand row, note gone');
  await p.screenshot({ path: 'tests/shots/offhand.png', clip: { x: 900, y: 240, width: 380, height: 640 } });
  await go('7'); ok((await count()).includes('6 of 60'), 'shaman: ' + await count());
  await go('2'); ok(await p.locator('.armor tbody tr').count() === 9 && (await count()).includes('of 54'), 'paladin still 9 rows, 54');
  await go('7');
  const cell = p.locator('.armor tbody tr').nth(8).locator('button[data-a=item]').first();
  await cell.click();
  ok(/Shaman, \w+ Main Hand: unlocked at base/.test(await p.textContent('.pending')), 'main hand unlock pending');
  await p.click('button[data-a=discard]');
  await p.click('button[data-a=unlockall]');
  ok((await count()).includes('60 of 60'), 'shaman unlock all: ' + await count());
  ok(await p.locator('button[data-a=unlockall]').isDisabled(), 'unlock all disables at full');
  await p.click('button[data-a=save]'); await p.waitForSelector('.banner.ok');
  const t = dec(save), A = items(orig), B = items(t);
  const add = B.filter((x) => !A.includes(x));
  ok(add.length === 54 && add.every((x) => x.startsWith('107')), 'added 54 shaman pieces');
  ok(A.every((x) => B.includes(x)), 'nothing removed');
  ok([0,1,2,3,4,5].every((r) => B.includes(`1079${r}0`)) && [0,1,2,3,4,5].every((r) => B.includes(`1078${r}0`)), 'off-hand and main-hand ids present');
  const o = orig.split('\n'), n = t.split('\n');
  ok(n.filter((l) => !o.includes(l)).length === 1, 'only items line changed');
  ok(errs.length === 0, 'no page errors');
  console.log(fails ? `${fails} FAILED` : 'ALL PASSED');
  await b.close();
})().catch((e) => { console.error(e); process.exit(1); });
