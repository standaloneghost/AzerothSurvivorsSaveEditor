const { chromium } = require('playwright');
const { execFileSync } = require('child_process');
const [url, save] = process.argv.slice(2);
const dec = (f) => execFileSync('python3', ['-I', 'tools/show_save.py', f], { encoding: 'utf8' });
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
const ln = (t, k) => t.split('\n').find((l) => l.startsWith(k + '|')) || '';
(async () => {
  const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1280, height: 900 } });
  const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  await p.goto(url); await p.waitForSelector('h2');
  const orig = dec(save);
  await p.click('button[data-a=caopen]');
  const d = await p.textContent('.dialog');
  ok(d.includes('except Wisp-herder and Rune-hound') && d.includes('every race'), 'dialog lists the additions');
  await p.screenshot({ path: 'tests/shots/ca2.png' });
  await p.click('button[data-a=caconfirm]'); await p.waitForSelector('.banner.ok');
  const t = dec(save);
  console.log(ln(t, 'perk')); console.log(ln(t, 'races')); console.log(ln(t, 'pets'));
  const q = Object.fromEntries(ln(t, 'perk').slice(5).split(',').map((x) => x.split(':')));
  const want = { rerolls: 3, banish: 3, skip: 1, opening: 1, veteran: 2, keen: 2, companion: 1, second: 1, leash: 3, paws: 3, instinct_gold: 1 };
  ok(Object.entries(want).every(([k, v]) => q[k] === String(v)), 'all perks at max');
  ok(!('instinct_wisps' in q) && !('instinct_runes' in q), 'wisp-herder and rune-hound not granted');
  ok(ln(t, 'races') === 'races|1,2,3,4,5,6,7,8', 'all races');
  ok(ln(t, 'pets') === ln(orig, 'pets'), 'selected companions unchanged');
  await p.click('button[data-a=page][data-v=rewards]');
  await p.click('button[data-a=rtab][data-v=Companions]');
  ok((await p.textContent('main')).includes('26 of 26 unlocked'), 'all 26 companions unlocked');
  ok(await p.locator('.warn').count() === 0, 'no purchase warning');
  ok(errs.length === 0, 'no page errors');
  console.log(fails ? `${fails} FAILED` : 'ALL PASSED');
  await b.close();
})().catch((e) => { console.error(e); process.exit(1); });
