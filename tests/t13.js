const { chromium } = require('playwright');
const { execFileSync } = require('child_process');
const [url, save] = process.argv.slice(2);
const dec = (f) => execFileSync('python3', ['-I', 'tools/show_save.py', f], { encoding: 'utf8' });
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
const ln = (t, k) => t.split('\n').find((l) => l.startsWith(k + '|')) || '';
(async () => {
  const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1280, height: 900 } });
  const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  await p.goto(url); await p.waitForSelector('h2');
  const orig = dec(save), t0 = Math.floor(Date.now() / 1000);
  await p.click('button[data-a=page][data-v=ach]');
  console.log((await p.textContent('.sub')).trim());
  await p.screenshot({ path: 'tests/shots/achall.png', clip: { x: 230, y: 70, width: 1050, height: 240 } });
  await p.click('button[data-a=achall]');
  ok((await p.textContent('.sub')).includes('125 of 125'), 'all 125 earned');
  ok(await p.locator('button[data-a=achall]').isDisabled(), 'button disables when complete');
  ok(await p.locator('input[data-c=ach]:not(:checked)').count() === 0, 'no unticked boxes on this page');
  await p.click('button[data-a=save]'); await p.waitForSelector('.banner.ok');
  const t = dec(save);
  const a0 = ln(orig, 'ach').slice(4).split(','), a1 = ln(t, 'ach').slice(4).split(',');
  const d0 = Object.fromEntries(ln(orig, 'achat').slice(6).split(',').map((x) => x.split('='))), d1 = Object.fromEntries(ln(t, 'achat').slice(6).split(',').map((x) => x.split('=')));
  ok(a0.every((x) => a1.includes(x)), 'existing achievements kept');
  ok(a0.every((x) => d0[x] === d1[x]), 'existing dates unchanged');
  ok(a1.filter((x) => !a0.includes(x)).every((x) => Math.abs(Number(d1[x]) - t0) < 60), 'new ones dated now');
  console.log('added', a1.length - a0.length, 'total', a1.length);
  const o = orig.split('\n'), n = t.split('\n');
  ok([...new Set(n.filter((l) => !o.includes(l)).map((l) => l.split('|')[0]))].sort().join() === 'ach,achat', 'only ach and achat changed');
  ok(errs.length === 0, 'no page errors');
  console.log(fails ? `${fails} FAILED` : 'ALL PASSED');
  await b.close();
})().catch((e) => { console.error(e); process.exit(1); });
